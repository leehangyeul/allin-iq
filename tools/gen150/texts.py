def rank_ko(r):
    return "AKQJT98765432"[12 - r].replace("T", "10")


def hand_desc(a, street, hero):
    m = a["made"]
    base = MADE_KO.get(m) or "핸드"
    if m == "toppair":
        k = a["kick"]
        base += " 좋은 키커" if k is not None and k >= 8 else " 약한 키커"
    if m == "high":
        if a["overs"] == 2: base = "오버카드 두 장"
        elif a["overs"] == 1: base = "오버카드 한 장"
        else: base = "하이카드"
    parts = [base]
    if street < 2:
        dr = []
        if a.get("fd") == "nut": dr.append("넛 플러시 드로우")
        elif a.get("fd") == "non": dr.append("플러시 드로우")
        if a.get("oesd"): dr.append("오픈엔드 스트레이트 드로우")
        elif a.get("gut"): dr.append("거트샷")
        if a["outs"] >= 4 and dr:
            parts.append(" + ".join(dr) + f" · 아웃츠 {a['outs']}장")
        elif a.get("bd_fd") and not dr:
            parts.append("백도어 플러시 드로우")
    return " ".join(parts[:1]) + ("  ·  " + parts[1] if len(parts) > 1 else "")


def board_desc(bi, street):
    hi = "AKQJT98765432"[12 - bi["top"]].replace("T", "10")
    if bi["paired"]: return "페어 보드"
    if bi["mono"]: return f"같은 무늬 세 장 {hi} 하이 보드"
    if street >= 1 and bi["maxsuit"] >= 3: return f"플러시 드로우가 열린 {hi} 하이 보드"
    if bi["wet"]: return f"드로우가 많은 {hi} 하이 보드"
    return f"마른 {hi} 하이 보드"


def pick(seq, seed):
    return seq[seed % len(seq)]


